import { tool } from "@opencode-ai/plugin"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { safeExec } from "../lib/exec-utils.ts"
import { parsePe, type PeSection } from "../lib/pe-utils.ts"
import {
  directoryFromContext,
  resolveFromDirectoryInsideWorkspace,
  resolveInsideWorkspace,
  workspaceRootFromContext,
} from "../lib/workspace-path.ts"

type RuntimeFunction = {
  beginRva: number
  endRva: number
  unwindRva: number
  size: number
}

type FunctionSeed = {
  beginRva: number
  endRva?: number
}

function normalizeRel(input: string) {
  return input.replace(/\\/g, "/")
}

function compact(text: string, max = 12000) {
  if (text.length <= max) return text
  const head = text.slice(0, Math.floor(max * 0.6))
  const tail = text.slice(text.length - Math.floor(max * 0.4))
  return `${head}\n...[truncated ${text.length - max} chars]...\n${tail}`
}

function u32(buf: Buffer, off: number) {
  return off + 4 <= buf.length ? buf.readUInt32LE(off) : 0
}

function parseRuntimeFunctions(buf: Buffer, section: PeSection): RuntimeFunction[] {
  if (section.rawSize < 12) return []
  const start = Math.min(section.rawPointer, buf.length)
  const end = Math.min(section.rawPointer + section.rawSize, buf.length)
  const entries: RuntimeFunction[] = []
  for (let off = start; off + 12 <= end; off += 12) {
    const beginRva = u32(buf, off)
    const endRva = u32(buf, off + 4)
    const unwindRva = u32(buf, off + 8)
    if (beginRva && endRva > beginRva && endRva - beginRva <= 0x1000000) {
      entries.push({ beginRva, endRva, unwindRva, size: endRva - beginRva })
    }
  }
  return entries
}

function ghidraScript(seeds: FunctionSeed[], imageBase: number, labelPrefix: string) {
  return `# Generated by ctf-rev-pe-recovery
# Seeds x64 functions from .pdata RUNTIME_FUNCTION entries or prologue fallback.
# Ghidra createFunction signatures vary by version; the script tries the
# current two-argument form first, then the older explicit-source form.
from ghidra.program.model.address import AddressSet
from ghidra.program.model.symbol import SourceType

fm = currentProgram.getFunctionManager()
af = currentProgram.getAddressFactory()
space = af.getDefaultAddressSpace()
entries = [
${seeds
  .map(
    (seed) =>
      `    (0x${(imageBase + seed.beginRva).toString(16)}, ${seed.endRva === undefined ? "None" : `0x${(imageBase + seed.endRva).toString(16)}`}),`,
  )
  .join("\n")}
]

created = 0
for index, (begin, end) in enumerate(entries):
    start = space.getAddress(hex(begin))
    if end is None:
        body = AddressSet(start, start)
    else:
        stop = space.getAddress(hex(end))
        body = AddressSet(start, stop)
    name = "${labelPrefix}_%04x" % index
    created_fn = None
    for candidate in (
        lambda: fm.createFunction(name, start, body, SourceType.IMPORTED),
        lambda: fm.createFunction(name, start, None, SourceType.IMPORTED),
        lambda: fm.createFunction(name, start, False),
    ):
        try:
            created_fn = candidate()
            break
        except TypeError:
            continue
    if created_fn is not None:
        created += 1

print("CTF_PDATA_RECOVERY created=%d total=%d" % (created, len(entries)))
`
}

function scanX64PrologueRvas(buf: Buffer, section: PeSection, maxCandidates = 2000): number[] {
  const start = Math.min(section.rawPointer, buf.length)
  const end = Math.min(section.rawPointer + section.rawSize, buf.length)
  const signatures = [
    [0x55, 0x48, 0x89, 0xe5],
    [0x40, 0x55],
    [0x48, 0x89, 0x5c, 0x24],
    [0x48, 0x83, 0xec],
    [0x48, 0x81, 0xec],
    [0x40, 0x53],
    [0x40, 0x56],
    [0x40, 0x57],
    [0x53, 0x48, 0x83, 0xec],
  ]
  const rvas: number[] = []
  for (let off = start; off < end; off++) {
    if (rvas.length >= maxCandidates) break
    const matched = signatures.some((signature) => {
      if (off + signature.length > end) return false
      for (let i = 0; i < signature.length; i++) {
        if (buf[off + i] !== signature[i]) return false
      }
      return true
    })
    if (matched) rvas.push(section.virtualAddress + (off - start))
  }
  return rvas
}

function executableSection(pe: ReturnType<typeof parsePe>, name?: string): PeSection | undefined {
  if (!pe) return undefined
  if (name) return pe.sections.find((section) => section.name.toLowerCase() === name.toLowerCase())
  return pe.sections.find(
    (section) => (section.characteristics & 0x20000000) !== 0 && (section.characteristics & 0x80000000) === 0,
  )
}

export default tool({
  description:
    "CTF rebuilt-PE recovery helper: parse .pdata RUNTIME_FUNCTION entries into x64 function seeds, generate a Ghidra recovery script and ReVa address list, and optionally run objdump in bounded batches for linear disassembly without one huge timeout.",
  args: {
    target: tool.schema.string().describe("Workspace-relative PE file path (on-disk or rebuilt from memory)."),
    outDir: tool.schema
      .string()
      .optional()
      .describe("Workspace-relative output directory. Default work/rev-pe-recovery."),
    linear: tool.schema.boolean().optional().describe("Run bounded objdump linear disassembly batches. Default false."),
    sectionName: tool.schema
      .string()
      .optional()
      .describe("Section to disassemble. Default first executable section (.text)."),
    startRva: tool.schema.string().optional().describe("Hex start RVA for linear disassembly, e.g. 0x1000."),
    endRva: tool.schema.string().optional().describe("Hex end RVA for linear disassembly."),
    chunkSize: tool.schema.number().optional().describe("Batch size in bytes. Default 65536."),
    maxChunks: tool.schema.number().optional().describe("Maximum objdump batches. Default 64."),
    fallback: tool.schema.boolean().optional().describe("Enable prologue fallback when .pdata is empty. Default true."),
    jsonOnly: tool.schema.boolean().optional().describe("Return JSON only. Default false."),
  },
  async execute(args, context) {
    const workspace = workspaceRootFromContext(context)
    const directory = directoryFromContext(context)
    const target = resolveFromDirectoryInsideWorkspace(directory, workspace, args.target)
    const buf = await readFile(target)
    const pe = parsePe(buf)
    if (!pe) throw new Error("target is not a valid PE/MZ file")

    const outDir = resolveInsideWorkspace(workspace, args.outDir || "work/rev-pe-recovery")
    await mkdir(outDir, { recursive: true })
    const pdataSection = pe.sections.find((section) => section.name.toLowerCase() === ".pdata")
    const functions = pdataSection ? parseRuntimeFunctions(buf, pdataSection) : []
    const fallbackEnabled = args.fallback !== false
    const executable = executableSection(pe, args.sectionName)
    const prologueSeeds =
      fallbackEnabled && functions.length === 0 && executable ? scanX64PrologueRvas(buf, executable) : []
    const seeds: FunctionSeed[] = [
      ...functions.map((fn) => ({ beginRva: fn.beginRva, endRva: fn.endRva })),
      ...prologueSeeds.map((beginRva) => ({ beginRva })),
    ]
    const ghidraPath = path.join(outDir, "recover_pdata.py")
    const revaPath = path.join(outDir, "pdata_addresses.txt")
    const prologuePath = path.join(outDir, "prologue_addresses.txt")
    await writeFile(ghidraPath, ghidraScript(seeds, pe.imageBase, prologueSeeds.length ? "fallback" : "pdata"), "utf8")
    await writeFile(
      revaPath,
      seeds.map((seed) => `0x${(pe.imageBase + seed.beginRva).toString(16)}`).join("\n") + (seeds.length ? "\n" : ""),
      "utf8",
    )
    if (prologueSeeds.length) {
      await writeFile(
        prologuePath,
        prologueSeeds.map((rva) => `0x${(pe.imageBase + rva).toString(16)}`).join("\n") + "\n",
        "utf8",
      )
    }

    const disasmPath = path.join(outDir, "linear_disasm.txt")
    const disasm: { chunks: number; bytes: number; errors: string[]; preview: string } = {
      chunks: 0,
      bytes: 0,
      errors: [],
      preview: "",
    }
    if (args.linear) {
      const section = executableSection(pe, args.sectionName)
      if (!section) throw new Error("no executable section found for linear disassembly")
      const startRva = args.startRva ? Number.parseInt(args.startRva, 16) : section.virtualAddress
      const endRva = args.endRva
        ? Number.parseInt(args.endRva, 16)
        : section.virtualAddress + Math.max(section.virtualSize, section.rawSize)
      if (!Number.isFinite(startRva) || !Number.isFinite(endRva) || endRva <= startRva) {
        throw new Error("invalid startRva/endRva range")
      }
      const chunkSize = Math.max(4096, Math.min(args.chunkSize ?? 65536, 0x100000))
      const maxChunks = Math.max(1, Math.min(args.maxChunks ?? 64, 256))
      const lines: string[] = []
      for (let i = 0; i < maxChunks; i++) {
        const chunkStart = startRva + i * chunkSize
        if (chunkStart >= endRva) break
        const chunkEnd = Math.min(chunkStart + chunkSize, endRva)
        const startAddr = `0x${(pe.imageBase + chunkStart).toString(16)}`
        const endAddr = `0x${(pe.imageBase + chunkEnd).toString(16)}`
        const result = await safeExec(
          "objdump",
          ["-d", `--start-address=${startAddr}`, `--stop-address=${endAddr}`, target],
          path.dirname(target),
          30000,
          4 * 1024 * 1024,
        )
        disasm.chunks++
        if (!result.ok) {
          disasm.errors.push(`chunk ${i}: ${result.output.slice(0, 300)}`)
          continue
        }
        lines.push(`;; chunk ${i} ${startAddr}-${endAddr}`)
        lines.push(result.output)
        disasm.bytes += Buffer.byteLength(result.output, "utf8")
      }
      const text = lines.join("\n")
      await writeFile(disasmPath, text, "utf8")
      disasm.preview = text.split(/\r?\n/).slice(0, 8).join("\n")
    }

    const payload = {
      schema_version: "ctf_rev_pe_recovery.v1",
      target,
      image_base: `0x${pe.imageBase.toString(16)}`,
      pe32_plus: pe.pe32Plus,
      sections: pe.sections.map((section) => ({
        name: section.name,
        rva: section.virtualAddress,
        size: section.virtualSize,
        entropy: section.entropy,
      })),
      pdata: {
        section: pdataSection
          ? {
              name: pdataSection.name,
              rva: pdataSection.virtualAddress,
              raw_size: pdataSection.rawSize,
            }
          : null,
        function_count: functions.length,
        functions: functions.slice(0, 200).map((fn) => ({
          begin: `0x${fn.beginRva.toString(16)}`,
          end: `0x${fn.endRva.toString(16)}`,
          unwind: `0x${fn.unwindRva.toString(16)}`,
          size: fn.size,
        })),
      },
      function_recovery: {
        pdata_functions: functions.length,
        fallback_used: prologueSeeds.length > 0,
        fallback_source: prologueSeeds.length ? "x64_prologue_scan" : null,
        fallback_functions: prologueSeeds.length,
      },
      outputs: {
        ghidra_script: normalizeRel(path.relative(directory, ghidraPath)),
        reva_addresses: normalizeRel(path.relative(directory, revaPath)),
        prologue_addresses: prologueSeeds.length > 0 ? normalizeRel(path.relative(directory, prologuePath)) : null,
        linear_disasm: args.linear ? normalizeRel(path.relative(directory, disasmPath)) : null,
      },
      disasm,
      next_actions: [
        prologueSeeds.length
          ? "No usable .pdata entries were found; the generated script now seeds functions from x64 prologue signatures."
          : "Run the Ghidra script (Window > Script Manager > recover_pdata.py) to create functions from RUNTIME_FUNCTION seeds.",
        `For ReVa, import ${prologueSeeds.length ? "prologue_addresses.txt" : "pdata_addresses.txt"} as function entry candidates before decompilation.`,
        "After seeding, use the linear_disasm.txt chunks for focused checker slices instead of one full disassembly.",
      ],
    }

    if (args.jsonOnly) return JSON.stringify(payload, null, 2)
    return compact(
      [
        "CTF_REV_PE_RECOVERY:",
        `- target: ${target}`,
        `- pe32_plus: ${pe.pe32Plus}`,
        `- image_base: ${payload.image_base}`,
        `- pdata_functions: ${functions.length}`,
        `- fallback_used: ${payload.function_recovery.fallback_used}`,
        `- fallback_functions: ${payload.function_recovery.fallback_functions}`,
        `- ghidra_script: ${payload.outputs.ghidra_script}`,
        `- reva_addresses: ${payload.outputs.reva_addresses}`,
        `- prologue_addresses: ${payload.outputs.prologue_addresses || "none"}`,
        `- linear_chunks: ${disasm.chunks}`,
        `- disasm_bytes: ${disasm.bytes}`,
        `- disasm_errors: ${disasm.errors.length}`,
        "pdata_functions:",
        ...(functions
          .slice(0, 40)
          .map((fn) => `- begin=0x${fn.beginRva.toString(16)} end=0x${fn.endRva.toString(16)} size=${fn.size}`) || [
          "- none",
        ]),
        "next_actions:",
        ...payload.next_actions.map((line) => `- ${line}`),
        "disasm_errors:",
        ...(disasm.errors.length ? disasm.errors.map((line) => `- ${line}`) : ["- none"]),
        "disasm_preview:",
        disasm.preview || "none",
      ].join("\n"),
    )
  },
})

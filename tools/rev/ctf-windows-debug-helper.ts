import { tool } from "@opencode-ai/plugin"
import { existsSync } from "node:fs"
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { safeExec, safeExecWithStreams } from "../lib/exec-utils.ts"
import {
  directoryFromContext,
  resolveFromDirectoryInsideWorkspace,
  resolveInsideWorkspace,
  workspaceRootFromContext,
} from "../lib/workspace-path.ts"

function normalizeRel(input: string) {
  return input.replace(/\\/g, "/")
}

function compact(text: string, max = 12000) {
  if (text.length <= max) return text
  const head = text.slice(0, Math.floor(max * 0.6))
  const tail = text.slice(text.length - Math.floor(max * 0.4))
  return `${head}\n...[truncated ${text.length - max} chars]...\n${tail}`
}

function splitBreakpoints(value?: string) {
  return (value || "")
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean)
}

function normalizeAddress(value: string) {
  const trimmed = value.trim()
  if (/^(0x)?[0-9a-fA-F]+$/.test(trimmed)) return trimmed
  return value
}

function cdbCommandFile(breakpoints: string[], commands: string[], stdinNote: boolean) {
  const lines = [
    ".symfix",
    ".reload",
    "sxe ld",
    "sxe epr",
    ...breakpoints.map((bp) => `bp ${normalizeAddress(bp)}`),
    ...(stdinNote ? ["$$ stdin is supplied through the runner after process creation"] : []),
    ...(commands.length ? commands : ["r", "k", "q"]),
  ]
  return lines.join("\r\n") + "\r\n"
}

function x64dbgCommandFile(breakpoints: string[], commands: string[]) {
  const lines = [
    "// Generated by ctf-windows-debug-helper",
    "// Load this file in x64dbg: File > Script or command line: script <path>",
    ...breakpoints.map((bp) => `bp ${normalizeAddress(bp)}`),
    "run",
    ...(commands.length ? commands : ["r", "dump", "pause"]),
  ]
  return lines.join("\r\n") + "\r\n"
}

function cdbRunnerScript() {
  return String.raw`
param([string]$Cdb,[string]$Target,[string]$Args,[string]$CommandFile,[string]$StdinFile)
$ErrorActionPreference = "Stop"
if (-not $Cdb -or -not (Test-Path -LiteralPath $Cdb)) { throw "cdb not found" }
if ($StdinFile -and (Test-Path -LiteralPath $StdinFile)) {
  $inputText = [System.IO.File]::ReadAllText($StdinFile)
  $inputText | & $Cdb -cf $CommandFile $Target $Args 2>&1
} else {
  & $Cdb -cf $CommandFile $Target $Args 2>&1
}
if ($LASTEXITCODE -ne 0) { throw "cdb exited with $LASTEXITCODE" }
`
}

function x64dbgLaunchScript() {
  return String.raw`
param([string]$X64Dbg,[string]$Target,[string]$CommandFile)
$ErrorActionPreference = "Stop"
if (-not $X64Dbg -or -not (Test-Path -LiteralPath $X64Dbg)) { throw "x64dbg not found" }
Write-Output "Launching x64dbg with target; load the generated script from the Script tab."
& $X64Dbg $Target
Write-Output "script: $CommandFile"
`
}

async function findCdb(cwd: string): Promise<string> {
  const candidates = [
    "cdb.exe",
    "C:\\Program Files (x86)\\Windows Kits\\10\\Debuggers\\x64\\cdb.exe",
    "C:\\Program Files\\Windows Kits\\10\\Debuggers\\x64\\cdb.exe",
    "C:\\Program Files (x86)\\Windows Kits\\10\\Debuggers\\x86\\cdb.exe",
  ]
  for (const candidate of candidates) {
    if (path.isAbsolute(candidate) && existsSync(candidate)) return candidate
  }
  const r = await safeExec("where", ["cdb.exe"], cwd, 5000)
  if (r.ok && r.output.trim() && !r.output.includes("<failed:")) {
    return r.output.split(/\r?\n/)[0].trim()
  }
  return ""
}

export default tool({
  description:
    "CTF Windows debugger helper: generate cdb/WinDbg command scripts and x64dbg script/launch stubs for stdin, breakpoints, register/memory inspection, and document the x64dbg GUI-only automation path.",
  args: {
    target: tool.schema.string().describe("Workspace-relative PE path to debug."),
    debugger: tool.schema
      .string()
      .optional()
      .describe("auto | cdb | x64dbg. Default auto: prefer cdb/WinDbg; otherwise emit x64dbg scripts."),
    breakpoints: tool.schema
      .string()
      .optional()
      .describe("Comma-separated hex addresses or symbols, e.g. 0x140001000,main."),
    commands: tool.schema
      .string()
      .optional()
      .describe("Newline-separated debugger commands after breakpoints, e.g. r, dq 0x140002000, p."),
    stdinText: tool.schema.string().optional().describe("Text to feed to the target after creation (cdb runner)."),
    targetArgs: tool.schema.string().optional().describe("Command-line arguments passed to the target."),
    outDir: tool.schema
      .string()
      .optional()
      .describe("Workspace-relative output directory. Default work/rev-windows-debug."),
    run: tool.schema.boolean().optional().describe("Run the cdb script if cdb is available. Default false."),
    timeoutMs: tool.schema.number().optional().describe("cdb run timeout. Default 60000, hard cap 600000."),
    jsonOnly: tool.schema.boolean().optional().describe("Return JSON only. Default false."),
  },
  async execute(args, context) {
    const workspace = workspaceRootFromContext(context)
    const directory = directoryFromContext(context)
    const target = resolveFromDirectoryInsideWorkspace(directory, workspace, args.target)
    const outDir = resolveInsideWorkspace(workspace, args.outDir || "work/rev-windows-debug")
    await mkdir(outDir, { recursive: true })
    const breakpoints = splitBreakpoints(args.breakpoints)
    const commands = (args.commands || "")
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(Boolean)
    const debuggerKind = (args.debugger || "auto").toLowerCase()
    if (!["auto", "cdb", "x64dbg"].includes(debuggerKind)) throw new Error(`unsupported debugger: ${args.debugger}`)

    const cdb = debuggerKind === "x64dbg" ? "" : await findCdb(workspace)
    const x64dbg =
      process.platform === "win32"
        ? [
            process.env.X64DBG_PATH,
            "C:\\Tools\\snapshot\\release\\x64\\x64dbg.exe",
            "C:\\Tools\\x64dbg\\x64\\x64dbg.exe",
          ].find((candidate) => candidate && existsSync(candidate)) ||
          process.env.X64DBG_PATH ||
          "C:\\Tools\\snapshot\\release\\x64\\x64dbg.exe"
        : ""

    const cdbCommandsPath = path.join(outDir, "cdb_commands.txt")
    const x64CommandFile = path.join(outDir, "x64dbg_commands.txt")
    const cdbRunner = path.join(outDir, "run_cdb.ps1")
    const x64Launcher = path.join(outDir, "launch_x64dbg.ps1")
    const stdinFile = path.join(outDir, "stdin.txt")

    await writeFile(cdbCommandsPath, cdbCommandFile(breakpoints, commands, Boolean(args.stdinText)), "utf8")
    await writeFile(x64CommandFile, x64dbgCommandFile(breakpoints, commands), "utf8")
    if (args.stdinText !== undefined) await writeFile(stdinFile, args.stdinText, "utf8")
    await writeFile(cdbRunner, cdbRunnerScript(), "utf8")
    await writeFile(x64Launcher, x64dbgLaunchScript(), "utf8")

    let runResult: unknown = null
    if (args.run && cdb) {
      const res = await safeExecWithStreams(
        "powershell",
        [
          "-NoProfile",
          "-ExecutionPolicy",
          "Bypass",
          "-File",
          cdbRunner,
          "-Cdb",
          cdb,
          "-Target",
          target,
          "-Args",
          args.targetArgs || "",
          "-CommandFile",
          cdbCommandsPath,
          "-StdinFile",
          args.stdinText !== undefined ? stdinFile : "",
        ],
        {
          timeoutMs: Math.max(5000, Math.min(args.timeoutMs ?? 60000, 600000)),
          cwd: outDir,
          maxBuffer: 8 * 1024 * 1024,
        },
      )
      runResult = {
        ok: res.ok,
        exit_code: res.exitCode,
        stdout: compact(res.stdout, 6000),
        stderr: compact(res.stderr, 2000),
      }
    }

    const payload = {
      schema_version: "ctf_windows_debug_helper.v1",
      target,
      debugger: cdb ? "cdb" : "x64dbg",
      cdb_path: cdb || null,
      x64dbg_path: existsSync(x64dbg) ? x64dbg : null,
      outputs: {
        cdb_commands: normalizeRel(path.relative(directory, cdbCommandsPath)),
        cdb_runner: normalizeRel(path.relative(directory, cdbRunner)),
        x64dbg_commands: normalizeRel(path.relative(directory, x64CommandFile)),
        x64dbg_launcher: normalizeRel(path.relative(directory, x64Launcher)),
        stdin: args.stdinText !== undefined ? normalizeRel(path.relative(directory, stdinFile)) : null,
      },
      run: runResult,
      notes: [
        "x64dbg.exe is a GUI debugger; it has no reliable headless -h/CLI automation path on this setup.",
        "Prefer cdb.exe/WinDbg for scriptable stdin + breakpoint + register/memory automation when the Windows SDK debugger is installed.",
        "For x64dbg, open the target, then load x64dbg_commands.txt from the Script tab; inspect registers with r and memory with dump.",
        "For the fast lane, use the generated cdb runner when available; otherwise use the generated x64dbg script manually.",
      ],
    }

    if (args.jsonOnly) return JSON.stringify(payload, null, 2)
    return compact(
      [
        "CTF_WINDOWS_DEBUG_HELPER:",
        `- target: ${target}`,
        `- debugger: ${payload.debugger}`,
        `- cdb_path: ${payload.cdb_path || "not found"}`,
        `- x64dbg_path: ${payload.x64dbg_path || "not found"}`,
        `- cdb_commands: ${payload.outputs.cdb_commands}`,
        `- cdb_runner: ${payload.outputs.cdb_runner}`,
        `- x64dbg_commands: ${payload.outputs.x64dbg_commands}`,
        `- x64dbg_launcher: ${payload.outputs.x64dbg_launcher}`,
        `- run: ${runResult ? "executed" : "not executed"}`,
        "notes:",
        ...payload.notes.map((line) => `- ${line}`),
        "run_result:",
        runResult ? JSON.stringify(runResult) : "none",
      ].join("\n"),
    )
  },
})
